-- Run from the repository root: lua Plugins/AutoBlueprint/Scripts/Tests/p0_scripts_test.lua
-- Tests Lua control flow with a fake UE facade, not UnLua reflection or asset persistence.
local pluginRoot = arg[1] or "Plugins/AutoBlueprint"

local function readFile(path)
    local file = assert(io.open(path, "rb"))
    local content = file:read("a")
    file:close()
    return content
end

local runner = readFile(pluginRoot .. "/Source/AutoBlueprintEditor/Private/Scripting/EditorLuaRunner.cpp")
local bootstrap = assert(runner:match('TEXT%(R"lua%((.-)%)lua"%)'), "C++ bootstrap not found")
local generateSource = readFile(pluginRoot .. "/Scripts/Lua/p0_generate.lua")
local errorSource = readFile(pluginRoot .. "/Scripts/Lua/p0_error.lua")

local function array(values)
    return { ToTable = function() return values end }
end

local function buildResult(success, compiled, saved, diagnostics)
    return {
        bSuccess = success,
        bCompiled = compiled,
        bSaved = saved,
        AssetPath = "/Game/UI/AutoBlueprintTests/WBP_Test.WBP_Test",
        CreatedAssets = array({ "/Game/UI/AutoBlueprintTests/WBP_Test.WBP_Test" }),
        SavedPackages = array(saved and { "/Game/UI/AutoBlueprintTests/WBP_Test" } or {}),
        UnsavedPackages = array(saved and {} or { "/Game/UI/AutoBlueprintTests/WBP_Test" }),
        Diagnostics = array(diagnostics or {})
    }
end

local function execute(source, filename, result)
    local output = {}
    local calls = 0
    local packagePath = "/Game/UI/AutoBlueprintTests/WBP_Test"
    local environment = setmetatable({
        AutoBlueprintTask = { source = source, chunkName = "@" .. filename, packagePath = packagePath },
        package = { path = "game/?.lua", cpath = "native/?.dll", searchers = {} },
        print = function(message) output[#output + 1] = message end,
        UE = {
            FAutoBlueprintSmokeTestRequest = function() return {} end,
            UAutoBlueprintLibrary = {
                BuildSmokeTestWidget = function(request)
                    calls = calls + 1
                    assert(request.PackagePath == packagePath)
                    assert(request.TitleText == "AutoBlueprint P0 - generated by Lua")
                    assert(request.ButtonText == "Confirm")
                    assert(request.bSave == true)
                    return result
                end
            }
        }
    }, { __index = _G })
    environment.load = function(chunk, name, mode)
        return load(chunk, name, mode, environment)
    end
    local ok, message = assert(load(bootstrap, "@AutoBlueprint/P0Runner", "t", environment))()
    assert(environment.AutoBlueprintTask == nil, "Host input should not remain globally accessible")
    assert(environment.package.path == "" and environment.package.cpath == "")
    assert(next(environment.package.searchers) == nil)
    return ok, message, calls, table.concat(output, "\n")
end

local ok, message, calls, output = execute(generateSource, "p0_generate.lua", buildResult(true, true, true))
assert(ok and message == nil and calls == 1)
assert(output:find("Saved package:", 1, true))
assert(output:find("Generated:", 1, true))

ok, message, calls, output = execute(generateSource, "p0_generate.lua", buildResult(false, true, false, {
    { Code = "PACKAGE_SAVE_FAILED", Message = "Disk is read-only" }
}))
assert(not ok and calls == 1)
assert(message:find("PACKAGE_SAVE_FAILED: Disk is read-only", 1, true))
assert(message:find("stack traceback:", 1, true))
assert(output:find("Unsaved package:", 1, true))
assert(not output:find("Generated:", 1, true))

ok, message = execute(generateSource, "p0_generate.lua", buildResult(true, true, false))
assert(not ok and message:find("without saving", 1, true))
ok, message = execute(generateSource, "p0_generate.lua", buildResult(true, false, true))
assert(not ok and message:find("without a successful compile", 1, true))
ok, message = execute(generateSource, "p0_generate.lua", buildResult(1, true, true))
assert(not ok and message:find("bSuccess must be a Lua boolean", 1, true))

ok, message, calls = execute(errorSource, "p0_error.lua")
assert(not ok and calls == 0)
assert(message:find("AUTOBLUEPRINT_P0_EXPECTED_ERROR", 1, true))
assert(message:find("p0_error.lua:", 1, true))
assert(message:find("stack traceback:", 1, true))

ok, message = execute("local =", "invalid_syntax.lua")
assert(not ok and message:find("invalid_syntax.lua:", 1, true))
ok, message = execute("return false", "invalid_module.lua")
assert(not ok and message:find("P0 script must return a table", 1, true))
ok, message = execute("return { run = function() return false end }", "failed_task.lua")
assert(not ok and message:find("P0 script must return true", 1, true))

print("PASS: 9 P0 Lua control-flow cases (mock UE facade; no engine validation)")
