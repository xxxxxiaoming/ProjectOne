-- Fixed P0 fixture using the shared SDK and P1 argument contract.
local api = require("auto_blueprint")
local module = {}

function module.run(arguments)
    assert(#arguments == 1, "INVALID_ARGUMENTS: p0_generate.lua requires one new package path")
    local request = UE.FAutoBlueprintSmokeTestRequest()
    request.PackagePath = arguments[1]
    request.TitleText = "AutoBlueprint P0 - generated by Lua"
    request.ButtonText = "Confirm"
    request.bSave = true
    api.buildSmokeTest(request)
    return true
end

return module
